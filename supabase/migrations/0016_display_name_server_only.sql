-- 0016: 表示名の変更をサーバー経由だけにする・表示名の規則を単純にする・問い合わせの個別削除
--       （docs/SPEC.md §9.18-1・§9.17、最終レビュー R23 重要1・重要2）
--
--   1. 表示名の変更はサーバー経由だけ（R23 重要1）。
--      - 旧 set_display_name(p_name text)（authenticated が本人のセッションで呼ぶ。auth.uid() の表示名を変える）を消し、
--        set_display_name(p_user_id uuid, p_name text) を作る。EXECUTE は service_role だけ。
--        Server Action（src/app/actions/display-name.ts）が本人の ID をサーバー側で確かめ（auth.getUser）、
--        アプリの検査（src/lib/domain/display-name.ts）を通した名前だけを service role の接続で送る（問い合わせと同じ作り）。
--        利用者が RPC を直接呼んでアプリの検査を回避することはできない。DB の検査は最後の砦として残す。
--   2. 表示名の規則を単純にする（アプリと DB で同じ。R23 重要1）。
--      - ZWNJ（U+200C）は全面禁止（contains_format_character に戻す。0014 で外したもの）。
--      - タグ文字は、Unicode の正式な地域旗の3つ（イングランド・スコットランド・ウェールズ）の並びと完全に一致するときだけ。
--      - ZWJ（U+200D）は前後が絵文字（Extended_Pictographic。前は肌の色の修飾子・VS16・3つの旗を遡る）のときだけ。
--      - 見える文字（Letter・Number・Punctuation・Symbol。ハングルの埋め字・点字の空白は数えない）が1つも無い名前は拒否
--        （結合文字だけの名前も拒否）。
--      正規表現で Unicode の性質を調べられないので、見える文字と絵文字は範囲の表（int4multirange）で持つ。
--      表は Unicode 17.0（アプリの実行環境の Unicode）から作り、src/lib/domain/display-name.test.ts が
--      「表 = 実行環境の \p{L}\p{N}\p{P}\p{S}（埋め字を除く）・\p{Extended_Pictographic}」であることを照合する。
--      アプリと DB が同じ判定になることは、同じ一覧（src/lib/domain/display-name.cases.ts と
--      supabase/tests/0016_display_name_server_only.sql）を両方に流して確かめる。
--      0015 の近似の関数（display_name_is_letter・display_name_is_invisible）は消す。
--      既存の表示名は書き換えない（本番のデータはまだ無い。SPEC §9.18）。
--   3. 問い合わせの個別削除 delete_contact_message(p_id uuid)（R23 重要2）。
--      運営が個別に削除するときと、バックアップから戻した後に、別に保管している台帳をもとに削除をやり直すときに使う。
--      消したら true、無ければ false（戻したバックアップに無い問い合わせで再適用が止まらないように）。service_role のみ。

