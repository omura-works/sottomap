-- =========================================================
-- 3. 並びの検査（src/lib/domain/display-name.ts の hasInvisibleSequence と同じ規則）
-- =========================================================
create or replace function public.display_name_has_invisible_sequence(p_text text)
returns boolean
language plpgsql
immutable
strict
parallel safe
set search_path = ''
as $$
declare
  -- Unicode の正式な地域旗の3つ（黒旗 ＋ タグ5文字 ＋ 終端）: イングランド（gbeng）・スコットランド（gbsct）・ウェールズ（gbwls）。
  c_england constant integer[] := array[127988, 917607, 917602, 917605, 917614, 917607, 917631];
  c_scotland constant integer[] := array[127988, 917607, 917602, 917619, 917603, 917620, 917631];
  c_wales constant integer[] := array[127988, 917607, 917602, 917623, 917612, 917619, 917631];
  v_cps integer[];
  v_n integer;
  v_i integer := 1;
  v_j integer;
  v_cp integer;
  v_next integer;
  v_slice integer[];
  v_visible boolean := false;
begin
  v_n := pg_catalog.char_length(p_text);
  v_cps := array(
    select pg_catalog.ascii(pg_catalog.substr(p_text, g.i, 1))
    from pg_catalog.generate_series(1, v_n) as g(i)
    order by g.i
  );

  while v_i <= v_n loop
    v_cp := v_cps[v_i];
    v_next := coalesce(v_cps[v_i + 1], -1);

    -- 黒旗の後にタグ文字が続くなら、3つの旗のどれかと完全に一致しなければ不可。
    if v_cp = 0x1F3F4 and v_next between 0xE0020 and 0xE007F then
      v_slice := v_cps[v_i:v_i + 6];
      if v_slice is distinct from c_england
         and v_slice is distinct from c_scotland
         and v_slice is distinct from c_wales then
        return true;
      end if;
      v_visible := true;
      v_i := v_i + 7;
      continue;
    end if;

    -- 3つの旗の外にあるタグ文字は不可。
    if v_cp between 0xE0020 and 0xE007F then
      return true;
    end if;

    if v_cp = 0x200D then
      -- 前: 3つの旗の終端なら絵文字（タグ文字は旗の中にしか置けない）。肌の色の修飾子・VS16 を遡って絵文字。後: 絵文字。
      v_j := v_i - 1;
      if coalesce(v_cps[v_j], -1) <> 0xE007F then
        while v_j >= 1 and (v_cps[v_j] = 0xFE0F or v_cps[v_j] between 0x1F3FB and 0x1F3FF) loop
          v_j := v_j - 1;
        end loop;
        if v_j < 1 or not public.display_name_is_pictographic(v_cps[v_j]) then
          return true;
        end if;
      end if;
      if v_next = -1 or not public.display_name_is_pictographic(v_next) then
        return true;
      end if;
    elsif public.display_name_is_visible(v_cp) then
      v_visible := true;
    end if;

    v_i := v_i + 1;
  end loop;

  return not v_visible;
end;
$$;

