create or replace function public.set_display_name(p_user_id uuid, p_name text)
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_name text;
begin
  if p_user_id is null then
    raise exception 'アカウントを指定してください' using errcode = '22023';
  end if;

  v_name := pg_catalog.regexp_replace(coalesce(p_name, ''), '^[[:space:]　]+|[[:space:]　]+$', '', 'g');

  -- 検査の順はアプリと同じ（書式文字 → 空 → 20文字 → 改行や制御文字 → 並び・見える文字 → メールアドレスの形）。
  if public.contains_format_character(v_name) then
    raise exception '表示名に見えない文字は使えません' using errcode = '22023';
  end if;
  if pg_catalog.char_length(v_name) = 0 then
    raise exception '表示名を入力してください' using errcode = '22023';
  end if;
  if pg_catalog.char_length(v_name) > 20 then
    raise exception '表示名は20文字以内で入力してください' using errcode = '22023';
  end if;
  -- 改行・制御文字と、Unicode の行区切り（U+2028）・段落区切り（U+2029）を拒否する。
  -- 見えない文字をソースに直接書くと転記で化けるため（R24 重要1）、chr() で指定する。
  if v_name ~ '[\u0001-\u001f\u007f-\u009f]'
     or pg_catalog.strpos(v_name, pg_catalog.chr(8232)) > 0
     or pg_catalog.strpos(v_name, pg_catalog.chr(8233)) > 0 then
    raise exception '表示名に改行や制御文字は使えません' using errcode = '22023';
  end if;
  if public.display_name_has_invisible_sequence(v_name) then
    raise exception '表示名に見えない文字は使えません' using errcode = '22023';
  end if;
  if v_name ~ '[^[:space:]@＠][@＠][^[:space:]@＠]' then
    raise exception '表示名にメールアドレスは使えません' using errcode = '22023';
  end if;

  update public.users set display_name = v_name where id = p_user_id;
  if not found then
    raise exception 'プロフィールが見つかりませんでした' using errcode = 'P0002';
  end if;

  return v_name;
end;
$$;

