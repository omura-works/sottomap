/** 8つの街の点（同じ座標系。slug と対応）。 */
export const HOKKAIDO_TOWNS: Readonly<Record<string, { x: number; y: number }>> = {
  sapporo: { x: 140, y: 238 },
  otaru: { x: 115, y: 228 },
  hakodate: { x: 70, y: 408 },
  asahikawa: { x: 220, y: 168 },
  furano: { x: 225, y: 218 },
  kushiro: { x: 375, y: 283 },
  obihiro: { x: 280, y: 278 },
  wakkanai: { x: 195, y: 43 },
};

export interface HokkaidoMapProps {
  /** 選ばれている街の slug。変わると灯りが前の点から次の点へ渡り、着いたら輪が1回にじむ。 */
  selectedSlug: string;
  /** 大きさは className か style で与える（例: 幅 112px・高さ 104px）。 */
  className?: string;
  style?: CSSProperties;
  /** 描かれたときに選ばれた街の灯りが灯る（初回表示の演出）。 */
  ignite?: boolean;
}

/**
 * 北海道の小さな地図（SPEC motion §2.10.1）。灯りは HTML の丸を地図の上に重ね、`translate` を
 * コンテナの大きさ（cqw / cqh）で置く。街が変わると `translate` の transition（`--spring-settle` 600ms）で渡る。
 */
export function HokkaidoMap({ selectedSlug, className, style, ignite = false }: HokkaidoMapProps) {
  const town = HOKKAIDO_TOWNS[selectedSlug];
  return (
    <div className={["hokkaido-map", className].filter(Boolean).join(" ")} style={style} aria-hidden="true">
      <svg viewBox="0 0 486 454" focusable="false" aria-hidden="true">
        <path className="hokkaido-coast" d={HOKKAIDO_PATH} />
        {Object.entries(HOKKAIDO_TOWNS).map(([slug, point]) => (
          <circle key={slug} className="hokkaido-town" cx={point.x} cy={point.y} r={4} />
        ))}
      </svg>
      {town ? (
        <span
          className={ignite ? "hokkaido-lamp hokkaido-lamp-ignite" : "hokkaido-lamp"}
          style={{ "--x": town.x, "--y": town.y } as CSSProperties}
        >
          <span className="hokkaido-lamp-halo" />
          {/* 着いたら1回だけにじむ輪。街が変わるたびに作り直して再生する。 */}
          <span key={selectedSlug} className="hokkaido-lamp-ring" />
          <span className="hokkaido-lamp-core" />
        </span>
      ) : null}
    </div>
  );
}
